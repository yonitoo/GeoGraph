from typing import List, Dict


def build_mcq_prompt(question: str, options: List[Dict[str, str]]) -> str:
    prompt = (
        "Ще ти бъде даден въпрос от затворен тип с 4 опции: A, B, C и D. "
        "Отговори като използваш само буквата на верния отговор.\n\n"
        f"Въпрос: {question}\n"
    )
    for option in options:
        prompt += f"{option['label']}) {option['text']}\n"
    prompt += "Отговор:"
    return prompt


def build_grounded_prompt(context_triples: List[str], user_query: str) -> str:
    if context_triples:
        context = "\n".join(
            f"{i + 1}. {triple}" for i, triple in enumerate(context_triples)
        )
    else:
        context = "Няма намерен специфичен контекст."

    return (
        "Използвай САМО предоставения контекст, за да отговориш на въпроса. "
        "Въпросът е от затворен тип (с варианти за отговор). Един факт от контекста "
        "може да подкрепя пряко верния вариант, ИЛИ да изключва останалите варианти "
        "(напр. при въпроси от типа „кое НЕ е вярно/не се отнася“, или при въпроси за "
        "несъответствие между двойки) — и двата случая се считат за достатъчно основание "
        "да отговориш. Отговори с '-' САМО ако контекстът е изцяло неотносим както към "
        "въпроса, така и към всички варианти за отговор.\n\n"
        "Контекст:\n"
        "---------------------\n"
        f"{context}\n"
        "---------------------\n\n"
        "Въпрос:\n"
        "---------------------\n"
        f"{user_query}\n"
        "---------------------\n\n"
        "Отговор: (САМО С ГОРНИЯ КОНТЕКСТ - ако е изцяло неотносим, отговори с '-')"
    )
